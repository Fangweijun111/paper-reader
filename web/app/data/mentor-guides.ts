function buildGuide(profile: MentorProfile): ChapterMentorNotes {
  return {
    1: `这一章先把整篇论文压成一条主线：${profile.core}。读完这里应该能够区分研究对象、作者要解决的失败模式，以及最终新增的能力。`,
    2: `背景部分不是罗列名词，而是在建立“为什么旧路线不够”的因果链：${profile.problem}。后面的方法模块都应当能对应回这条问题链，否则只是额外工程。`,
    3: `问题定义最需要抓住的是学习边界：${profile.boundary}。先明确输入、输出和更新对象，才能判断论文是在训练模型、优化动作，还是只更新外部记忆。`,
    4: `方法流程可以按先后关系理解：${profile.flow}。这个顺序决定了信息何时产生、何时被使用，也解释了为什么某些模块不能互换或省略。`,
    5: `核心机制真正承担的工作是：${profile.mechanism}。阅读模块图时不要只记名称，要顺着输入、状态变化和输出看它如何影响后续决策。`,
    6: `公式与算法是在把前述机制变成可执行约束：${profile.equations}。实现时应逐一对应变量、状态更新与停止条件，不能把概念公式误当成已经验证的规律。`,
    7: `实验部分要把正面证据和限制一起看。最关键的支持是：${profile.evidence}；同时必须保留这条警告：${profile.caution}。这样才知道结果究竟证明到哪一步。`,
    8: `成本分析的重点不是简单回答“需不需要 GPU”，而是定位主要开销：${profile.cost}。最小复现应优先保留决定结论的环节，而不是复制作者的全部规模。`,
    9: `贡献需要按证据强度排序：${profile.contribution}。把核心方法、有效实验和工程集成分开，能避免把系统复杂度本身误写成算法创新。`,
    10: `相关工作比较要看更新对象与运行闭环，而不只看标题词汇：${profile.relation}。这种比较能说明它与 RAG、RL、世界模型或 Agent planning 的真正边界。`,
    11: `复现时最先建立可归因对照：${profile.reproduction}。只有固定底座、数据与预算，再改变目标模块，才能知道性能变化来自哪里。`,
    12: `新论文方向应当补原文尚未闭合的证据：${profile.opportunity}。验证时既要测平均收益，也要测失败、负迁移、成本和长期稳定性。`,
    13: `检查自己是否读懂时，用三句话复述：方法主线是“${profile.core}”；最强证据是“${profile.evidence}”；最需要警惕的是“${profile.caution}”。三者缺一，就还只是记住了论文话术。`,
  };
}

